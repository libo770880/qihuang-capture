/** 由全量药名生成种子规则：自费 > □限定 > 普通甲类 */
function buildSeedRows(allNames) {
  const rows = [];
  for (const name of allNames) {
    if (SELF_PAID[name]) {
      rows.push({ name, payType: '自费', note: SELF_PAID[name] });
    } else if (SQUARE.includes(name)) {
      rows.push({ name, payType: '甲类', limit: SQUARE_LIMIT, note: '国家目录□品种' });
    } else {
      rows.push({ name, payType: '甲类' });
    }
  }
  return rows;
}

