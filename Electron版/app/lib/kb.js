// 用户自定义 OCR 纠错（后台维护，knowledge/ocrfixes.json）：错字名 → 正确写法
// 可覆盖内置表；目标须为知识库已有药名/别名，否则忽略
let USER_OCR_FIX = {};
function setOcrFixes(arr) {
  USER_OCR_FIX = {};
  for (const it of (arr || [])) {
    const w = String((it && (it.w || it.wrong || it.name)) || '').trim();
    const r = String((it && (it.r || it.right || it.to)) || '').trim();
    if (w && r && w !== r) USER_OCR_FIX[w] = r;
  }
  rebuildMaps();
  return Object.keys(USER_OCR_FIX).length;
}
function getUserOcrFixes() { return Object.entries(USER_OCR_FIX).map(([w, r]) => ({ w, r })); }

// 字符级确定性变体（正确名 → OCR 错字名）：
// 朮 为「术」繁体误识；灸/炙 形近（灸仅用于针灸，不会是药名前缀）
function ocrVariantsOf(name) {
  const v = [];
  if (!name) return v;
  if (name.includes('术')) v.push(name.split('术').join('朮'));
  if (name.startsWith('炙')) v.push('灸' + name.slice(1));
  return v;
}

// 某正名的全部 OCR 错字别名（字符变体含其别名 + 内置/用户核对表反查，值可为正名或其别名）
function ocrAliasesFor(canonName, extraAliases) {
  const out = [];
  const has = new Set([...(extraAliases || []), canonName]);
  const push = (n) => { if (n && !has.has(n) && !out.includes(n)) { out.push(n); has.add(n); } };
  for (const n of [canonName, ...(extraAliases || [])]) for (const v of ocrVariantsOf(n)) push(v);
  for (const [w, r] of Object.entries(OCR_HERB_FIX)) if (r === canonName || (extraAliases || []).includes(r)) push(w);
  for (const [w, r] of Object.entries(USER_OCR_FIX)) if (r === canonName || (extraAliases || []).includes(r)) push(w);
  return out;
}

// ===== OCR 文本级纠错：把 OCR 错字全名直接替换为正确写法（仅全名替换，不逐字盲改） =====
let ocrTextFixMap = null;
function ocrTextFixes() {
  if (ocrTextFixMap) return ocrTextFixMap;
  if (!canonCache) rebuildMaps();
  const m = {};
  for (const k of Object.keys(canonCache)) for (const v of ocrVariantsOf(k)) if (!m[v] && canonCache[v]) m[v] = k;
  for (const [w, r] of Object.entries(OCR_HERB_FIX)) if (!m[w] && canonCache[w]) m[w] = r;
  for (const [w, r] of Object.entries(USER_OCR_FIX)) if (canonCache[w]) m[w] = r; // 用户覆盖内置
  ocrTextFixMap = Object.entries(m).sort((a, b) => b[0].length - a[0].length); // 长名优先（麸炒白朮 先于 白朮）
  return ocrTextFixMap;
}
// ===== 动态形近纠错（剂量上下文约束）=====
// 紧邻剂量（12g / 10克）的中文段若非已知药名（正名/别名池），按中药库形近纠错：
//  ① 空格归并：系统 OCR 逐字空格输出（「制 吴 萸 3g」→「制吴萸 3g」），只并单行空格/Tab 不跨行；
//  ② 名内数字吞并：「太子 0」——名内字被识成孤立数字且后非剂量 → 前缀补全（太子→太子参）；
//  ③ 同长度形近：1 字差任意长度；2 字差限 ≥4 字、或 3 字且末字相同（OCR 常保住末字：的解刺→皂角刺）；
//  ④ 前缀补全：截断名（法半→法半夏、制吴萸→制吴茱萸）唯一补全才改；
//  ⑤ 剥炮制前缀二级：炒六祺曲 → 炒 + 六神曲；
//  ⑥ 同音仲裁：同字差多候选时取拼音一致者（白莹→白英 而非 白芷）。
// 唯一（或同音唯一）才改，否则保持原文绝不盲改。
const HERB_PRE_TOKENS = ['麸炒', '酒洗', '酒炒', '盐炒', '姜炒', '土炒', '清炒', '炒', '焦', '酒', '盐', '姜', '蜜', '醋', '煅', '煨', '烫', '蒸'];
// 单字炮制/制法前缀：OCR 逐字空格下「炙 甘草」「生 甘草」须粘连；而「岁 主诉」这类非前缀单字不得粘
const OCR_SINGLE_PREFIX = new Set([...HERB_PRE_TOKENS.filter(p => p.length === 1),
  '生', '熟', '制', '法', '清', '鲜', '干', '炮', '炙', '土', '米', '麸']);
let _pyFn = null;
function pyNoTone(s) { // 汉字串 → 无声调拼音（小写串）；pinyin-pro 不可用时返回 ''
  if (_pyFn === null) { try { _pyFn = require('pinyin-pro').pinyin; } catch (e) { _pyFn = false; } }
  if (!_pyFn) return '';
  try { return (_pyFn(s, { toneType: 'none', type: 'array', nonZh: 'consecutive' }) || []).join(''); } catch (e) { return ''; }
}
// OCR 逐字空格归并（共用）：只并「间隔两侧出现单字片段」的空隙（逐字空格特征：「制 吴 萸」「白 花 蛇 舌 草」），
// 多字词之间的正常空格必须保留——否则「创伤病 气血瘀证 西医诊断」会被粘成一个超长片段，
// 后面的术语库约束纠错层（fixTermsByLibrary）就拿不到词边界，证型/诊断纠错会整层失效。
// 不跨行（\n 不参与），剂量数字不受影响。
function mergeOcrSpacing(s) {
  // 正则须匹配「完整的、含空格的中文串」（[CJK]+ 后跟若干 (空格+CJK)+）；
  // 若写成「CJK + (空格+CJK)+」只会两两匹配，逐次替换仍会把空格全部吃掉。
  return String(s || '').replace(/[\u3400-\u4dbf\u4e00-\u9fa5·]+(?:[ \t]+[\u3400-\u4dbf\u4e00-\u9fa5·]+)+/g, (run) => {
    const parts = run.split(/[ \t]+/);
    const merged = [];
    let buf = [];
    const flush = () => { if (buf.length) { merged.push(buf.join('')); buf = []; } };
    for (const p of parts) {
      if (p.length === 1) { buf.push(p); continue; }   // 单字片段：累积为「逐字空格」组
      if (buf.length > 1) flush();                     // 连续单字组先各自归并，不与多字词粘连
      if (buf.length === 1 && OCR_SINGLE_PREFIX.has(buf[0])) { buf.push(p); flush(); } // 炮制前缀（炙 甘草→炙甘草）
      else { flush(); merged.push(p); }                // 其余单字（岁 主诉）保持原有空格
    }
    flush();
    return merged.join(' ');
  });
}

// 规格/剂型守卫词：HIS 处方表「规格」列的值（饮片 10g 型）紧邻剂量，会被形近层误改成
// 真实药名（饮片→冰片，1 字差、同尾「片」、唯一命中）——剂型词不是错字药名，直接放行
const SPEC_GUARD_RE = /^(?:中药饮片|饮片|配方颗粒|颗粒|免煎)$/;

function fixHerbFuzzyByDose(out, fixes) {
  // canon = 全名映射（含错字注入键）；cleanSet/pool = 错字注入前的干净键集（正名+合法别名+用户库）。
  // 候选池必须干净：注入键会制造假候选（美仁朴 的 羡厚朴/姜院朴）；
  // 待纠段命中注入键（白莹）时按错字处理直接归到正名，而不是原样放过
  const canon = getCanon();
  const cleanSet = new Set(getCleanCanonKeys());
  const pool = [...cleanSet];
  // ① 空格归并（系统 OCR「白 花 蛇 舌 草」→「白花蛇舌草」；多字词间空格保留，见 mergeOcrSpacing）
  out = mergeOcrSpacing(out);
  // ② 名内孤立数字吞并：「太子 0」→ 前缀补全；已是药名则保留原样（防误删无单位剂量「当归 9」）
  out = out.replace(/([\u3400-\u4dbf\u4e00-\u9fa5]{2,6})[ \t]+([0-9])(?![0-9])(?![ \t]*[gG克])/g, function (m, seg, d) {
    if (canon[seg]) return m; // 段本身是药名：不动（数字可能是无单位剂量）
    const c = completeUnique(seg);
    if (c) { fixes.push(seg + d + '→' + c); return c; }
    return m;
  });
  function fuzzyBest(seg) {
    const n = seg.length;
    let bestDiff = 99; const ties = [];
    for (const name of pool) {
      if (name.length !== n) continue;
      let diff = 0;
      for (let i = 0; i < n; i++) if (seg[i] !== name[i] && ++diff > 2) { diff = 99; break; }
      if (diff === 99) continue;
      const ok = diff === 1 || (diff === 2 && (n >= 4 || seg[n - 1] === name[n - 1]));
      if (!ok) continue;
      if (diff < bestDiff) { bestDiff = diff; ties.length = 0; ties.push(name); }
      else if (diff === bestDiff) ties.push(name);
    }
    if (!ties.length) return null;
    if (ties.length === 1) return ties[0];
    // ⑥ 同音仲裁：同字差多候选 → 拼音一致者唯一才取（白莹→白英，排除白芷）
    const segPy = pyNoTone(seg);
    if (segPy) {
      const homo = ties.filter(t => pyNoTone(t) === segPy);
      if (homo.length === 1) return homo[0];
    }
    return null;
  }
  function completeUnique(seg) {
    if (seg.length < 2) return null;
    let cand = null;
    for (const name of pool) {
      if (name.length > seg.length && name.startsWith(seg)) { if (cand) return null; cand = name; }
    }
    return cand;
  }
  // 名内漏字补全：制吴萸 → 制吴茱萸（候选名删去恰好一个字符后与段相等，且唯一）
  function deleteOneUnique(seg) {
    if (seg.length < 2) return null;
    let cand = null;
    for (const name of pool) {
      if (name.length !== seg.length + 1) continue;
      let i = 0, j = 0, skipped = false, ok = true;
      while (i < seg.length && j < name.length) {
        if (seg[i] === name[j]) { i++; j++; }
        else if (!skipped) { skipped = true; j++; }
        else { ok = false; break; }
      }
      if (!ok || i !== seg.length) continue;
      if (name.length - j !== (skipped ? 0 : 1)) continue;
      if (cand) return null;
      cand = name;
    }
    return cand;
  }
  return out.replace(/([\u3400-\u4dbf\u4e00-\u9fa5·]{2,8})(?=\s*\d{1,3}(?:\.\d)?\s*[gG克])/g, function (seg0) {
    let seg = seg0.replace(/·/g, '');
    if (!seg) return seg0;
    if (cleanSet.has(seg)) return seg0;           // 正名/合法别名（北柴胡/茯苓块）：保持处方原文
    if (canon[seg]) {                            // 错字注入键（白止→白芷、白莹→白英）：直接归正名
      fixes.push(seg + '→' + canon[seg]);
      return canon[seg];
    }
    // ③'' 规格/剂型守卫：饮片/颗粒 等剂型词不是错字药名（否则形近层 饮片→冰片）
    if (SPEC_GUARD_RE.test(seg)) return seg0;
    // ⑤'' 炮制品名提前放行：炒莱菔子/炒酸枣仁/麸炒白术 —— 剥前缀后是正名/合法别名 → 原样保留。
    // 必须在形近层之前：4 字段允许 2 字差，会把 炒莱菔子 误改成 炒苍耳子、麸炒白术 改成 炒苍术 等
    for (const pre of HERB_PRE_TOKENS) {
      if (seg.startsWith(pre) && seg.length - pre.length >= 2 && cleanSet.has(seg.slice(pre.length))) return seg0;
    }
    // 名内混入数字（太子0参）：剥离后再试
    const noDig = seg.replace(/[0-9]/g, '');
    if (noDig && noDig !== seg) {
      if (canon[noDig]) { fixes.push(seg + '→' + noDig); return noDig; }
      seg = noDig;
    }
    let cand = fuzzyBest(seg);
    if (!cand) cand = completeUnique(seg); // ④ 尾部截断补全（法半→法半夏）
    if (!cand) cand = deleteOneUnique(seg); // ④' 名内漏字补全（制吴萸→制吴茱萸）
    if (!cand) {
      // ⑤ 剥炮制前缀再对剩余部分形近/补全（炒六祺曲 → 炒 + 六神曲）
      for (const pre of HERB_PRE_TOKENS) {
        if (!seg.startsWith(pre)) continue;
        const rest = seg.slice(pre.length);
        if (rest.length < 2) break;
        const c2 = fuzzyBest(rest) || completeUnique(rest) || deleteOneUnique(rest);
        if (c2) { cand = pre + c2; break; }
        break; // 只试最长可用前缀一次
      }
    }
    if (!cand) return seg0;
    fixes.push(seg + '→' + cand);
    return cand;
  });
}

function fixOcrText(text, medTerms) {
  let out = String(text || '');
  // 前置归一：系统 OCR 逐字空格输出（「制 吴 萸」「浙 风 号」），归并后静态错字表/形近层才可能命中；
  // 归并策略见 mergeOcrSpacing（多字词之间的正常空格保留，否则术语库约束纠错层拿不到词边界）
  out = mergeOcrSpacing(out);
  const fixes = [];
  const realNames = getHerbMap(); // 守卫用真实药名/别名表（不含 OCR 错字注入键，否则守卫自失效）
  // 守卫辅助：剥炮制前缀后查库（炒酸枣仁 含 枣仁 → 剥「炒」后 酸枣仁 是真药名 → 该处不替换）
  const stripPre = (s) => {
    for (const pre of HERB_PRE_TOKENS) {
      if (s.startsWith(pre) && s.length - pre.length >= 2) return s.slice(pre.length);
    }
    return s;
  };
  for (const [w, r] of ocrTextFixes()) {
    if (!out.includes(w)) continue;
    // 防误伤守卫：命中处所在的完整中文词段本身是真实药名（如 牡丹皮 含 丹皮、炒酸枣仁 含 枣仁）→ 该处不替换
    const parts = out.split(w);
    let n = 0;
    out = parts.map((seg, i) => {
      if (i === parts.length - 1) return seg;
      const before = (seg.match(/[一-龥]+$/) || [''])[0];
      const after = (parts[i + 1].match(/^[一-龥]+/) || [''])[0];
      const full = before + w + after;
      const hit = realNames[full] || (before && realNames[before + w]) || (after && realNames[w + after])
        || realNames[stripPre(full)] || (before && realNames[stripPre(before + w)]);
      if (hit) return seg + w;
      n++; return seg + r;
    }).join('');
    if (n) fixes.push(w + '→' + r);
  }
  out = fixHerbFuzzyByDose(out, fixes);
  return fixMedicalText(out, fixes, medTerms);
}

// ===== 通用医学术语纠错（第二层）：目标"零差错" =====
// 思路：OCR 引擎不可能 0 差错，但识别结果必须落在标准术语库上——
// ① 繁体/异体字归一（髖→髋、損→损） ② 损伤类词模式纠错（射挫伤→肘挫伤、员伤→损伤、髋部叶损伤→髋部损伤）
// ③ 证型/诊断库约束：未知片段若与标准术语存在唯一受限近邻（编辑距离≤1，或多候选时取"漏字包含"唯一解）即纠正
// 全部替换确定性、可回溯（fixes 明细入库），不命中则保持原文绝不盲改。
const OCR_CHAR_VARIANTS = { '髖': '髋', '損': '损', '傷': '伤', '証': '证', '癥': '症' };
const ANATOMY = ['头', '肘', '髋', '踝', '肩', '膝', '腕', '腰', '颈', '胸', '背', '腿', '足', '指', '趾',
  '头部', '肘部', '髋部', '踝部', '肩部', '膝部', '腕部', '腰部', '颈部', '胸部', '腹部',
  '脊柱', '腰椎', '颈椎', '肩胛', '前臂', '上臂', '小腿', '大腿', '手指', '足趾',
  '尺骨', '桡骨', '股骨', '胫骨', '腓骨', '跟骨', '锁骨', '肋骨', '骨盆', '下颌', '颅脑'];
const INJ_SUFFIX = ['挫伤', '损伤', '扭伤', '拉伤', '脱位', '裂伤', '擦伤', '血肿', '劳损', '撞伤', '挫裂伤', '扭挫伤', '撕脱伤', '骨折'];
// 偏旁脱落型误识：OCR 只识出字的右部件（损→员、挫→坐 等），置于"X伤"上下文中确定性还原
const INJ_RIGHT_PART = { '员': '损', '坐': '挫', '丑': '扭', '立': '拉', '童': '撞', '列': '裂', '察': '擦' };
// 形近字误识（仅限损伤词前缀上下文，避免误伤放射科等正常词）：射→肘
const INJ_CONFUSABLE = { '射': '肘', '村': '肘' };

function fixMedicalText(text, fixes, medTerms) {
  let out = String(text || '');
  // ① 繁体/异体字归一
  const norm = out.replace(/[髖損傷証癥]/g, c => OCR_CHAR_VARIANTS[c] || c);
  if (norm !== out) { fixes.push('繁体/异体字归一'); out = norm; }
  const partCh = '头肘髋踝肩膝腕腰颈胸背腿足';
  const sufAlt = INJ_SUFFIX.join('|');
  // ② 偏旁脱落："员伤"→"损伤"（X伤 且 X 为已知右部件）
  out = out.replace(/([^\s，。；、：（()0-9a-zA-Z])伤/g, (m, x) => {
    if (INJ_RIGHT_PART[x]) { fixes.push(x + '伤→' + INJ_RIGHT_PART[x] + '伤'); return INJ_RIGHT_PART[x] + '伤'; }
    return m;
  });
  // ③ 部位+部+杂字+损伤词 → 去杂字："髋部叶 损伤"→"髋部损伤"（的/之等为合法字不删）
  const reJunk = new RegExp('([' + partCh + '])部[ ]?([^\\s，。；、（）()0-9的之损挫扭拉撞裂擦血劳骨脱撕]{1})([ ]?)(?=' + sufAlt + ')', 'g');
  out = out.replace(reJunk, (m, p, j) => { fixes.push(p + '部' + j + '→' + p + '部'); return p + '部'; });
  // ④ 形近字（仅损伤词前缀上下文）："射挫伤"→"肘挫伤"
  const reConf = new RegExp('[' + Object.keys(INJ_CONFUSABLE).join('') + '](?=' + sufAlt + ')', 'g');
  out = out.replace(reConf, (m) => { fixes.push(m + '→' + INJ_CONFUSABLE[m]); return INJ_CONFUSABLE[m]; });
  // ⑤ "诊断过" → "诊断："（冒号+编号黏连误识，恢复后再由标点容错解析）
  out = out.replace(/(诊\s*断)\s*过/g, (m, a) => { fixes.push(a + '过→' + a + '：'); return a + '：'; });
  // ⑤b 通用损伤/体征术语库纠偏：含医学语素的未知词 → 唯一近邻术语（损伍→损伤、骨折斤→骨折等）
  out = fixInjuryLexicon(out, fixes);
  // ⑥ 证型/诊断库约束纠错（传入标准术语库时）
  if (medTerms && Array.isArray(medTerms.syndromes) && Array.isArray(medTerms.diags)) {
    const terms = [...new Set([...medTerms.syndromes, ...medTerms.diags])].filter(t => t && t.length >= 3 && t.length <= 8 && !/[\s，。；：:、（）()]/.test(t));
    if (terms.length) out = fixTermsByLibrary(out, terms, fixes, medTerms.syndCtx || [], medTerms.syndSupport || null);
  }
  return { text: out, fixes };
}

// 通用术语库（损伤/体征词，可持续扩充）：仅"整块"二字词纠偏——按虚词/非汉字切分后恰好独立的词
// （防止长词内部滑窗误纠：气血瘀证的"血瘀"、髋部损伤的"部损"绝不改）
// 防误伤：候选须与错词共享一字（损伍→损伤 ✓），且库内收录常见合规词避免"唯一近邻"误判
const INJ_LEXICON = ['损伤', '挫伤', '扭伤', '拉伤', '撞伤', '擦伤', '裂伤', '撕脱伤', '挫裂伤', '扭挫伤',
  '脱位', '脱臼', '错位', '骨折', '血肿', '劳损', '肿胀', '瘀斑', '淤斑', '瘀血', '淤血', '压痛', '疼痛', '麻木', '受限',
  '胀痛', '钝痛', '绞痛', '刺痛', '灼痛', '酸痛', '隐痛', '闷痛', '头痛', '腹痛', '腰痛', '内伤', '创伤', '伤痛', '伤口',
  '出血', '咯血', '便血', '尿血', '活血', '止血', '凉血'];
const MED_ANCHOR = /[损挫扭拉撞擦裂撕脱错骨折血肿劳胀瘀淤压痛麻]/;
function fixInjuryLexicon(text, fixes) {
  return String(text).split(/([\u4e00-\u9fa5]+)/).map(seg => {
    if (!seg || !/[\u4e00-\u9fa5]/.test(seg)) return seg;
    return seg.split(/([的之与和及或于])/).map(part => {
      if (part.length !== 2 || /^[的之与和及或于]$/.test(part)) return part; // 只纠恰好独立的二字块
      const win = part;
      if (INJ_LEXICON.includes(win)) return win;
      if (!MED_ANCHOR.test(win)) return win;
      const cands = INJ_LEXICON.filter(t => t.length === 2 && t !== win && editDistLE(win, t, 1)
        && (t[0] === win[0] || t[1] === win[1])); // 须共享一字：错的是其中一个字
      if (cands.length === 1) {
        fixes.push(win + '→' + cands[0]);
        return cands[0];
      }
      return win; // 不唯一 → 绝不盲改
    }).join('');
  }).join('');
}

// 有界编辑距离：dist(a,b) ≤ max 时返回 true（提前剪枝）
function editDistLE(a, b, max) {
  const n = a.length, m = b.length;
  if (Math.abs(n - m) > max) return false;
  const dp = [];
  for (let i = 0; i <= n; i++) dp.push(new Array(m + 1).fill(0)), dp[i][0] = i;
  for (let j = 0; j <= m; j++) dp[0][j] = j;
  for (let i = 1; i <= n; i++) {
    for (let j = 1; j <= m; j++) {
      dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
    if (Math.min(...dp[i]) > max) return false; // 行最小值已超界，剪枝
  }
  return dp[n][m] <= max;
}
function isSubseq(a, b) { // a 的全部字符是否按序出现在 b 中（漏字场景：气血瘀证 ⊂ 气滞血瘀证）
  let i = 0;
  for (let j = 0; j < b.length && i < a.length; j++) if (b[j] === a[i]) i++;
  return i === a.length;
}
// 片段级术语库纠错：按标点/空白切分，非库内片段若与标准术语唯一近邻 → 替换
// syndCtx：当前诊断关联的证型（多候选歧义时用上下文收敛，如 气血瘀证 在"创伤病"下 → 气滞血瘀证）
// syndSupport：证型全库支持度（诊断/症状关联次数），上下文缺失或仍歧义时按支持度唯一最大收敛
function fixTermsByLibrary(text, terms, fixes, syndCtx, syndSupport) {
  const tset = new Set(terms);
  const ctx = new Set(syndCtx || []);
  const sup = syndSupport || null;
  return String(text).split(/([\s，。；：:、（）()\-—～~·0-9a-zA-Z.]+)/).map(tok => {
    if (!tok || /^[\s，。；：:、（）()\-—～~·0-9a-zA-Z.]+$/.test(tok)) return tok;
    if (tok.length < 3 || tok.length > 8 || tset.has(tok)) return tok;
    let cands = terms.filter(t => t !== tok && Math.abs(t.length - tok.length) <= 1 && editDistLE(tok, t, 1));
    if (cands.length !== 1) {
      // 多候选时取"漏字"解：片段是候选的按序子串且长度差 ≤2（气血瘀证 ⊂ 气滞血瘀证）
      const sub = terms.filter(t => t.length > tok.length && t.length - tok.length <= 2 && isSubseq(tok, t));
      const uniq = [...new Set(cands.concat(sub))];
      if (uniq.length === 1) cands = uniq;
      else {
        // 仍歧义 → ① 诊断关联证型收敛：分型范围内唯一即改
        const inCtx = uniq.filter(t => ctx.has(t));
        if (inCtx.length === 1) { fixes.push(tok + '→' + inCtx[0]); return inCtx[0]; }
        // ② 证型库支持度收敛：上下文歧义或缺失时，关联次数唯一最大才改（气滞血瘀证 26 次 vs 气虚血瘀证 0 次）
        const pool = inCtx.length > 1 ? inCtx : (sup ? uniq : null);
        if (pool) {
          let best = null, bestN = -1, tie = false;
          for (const t of pool) { const n = (sup && sup[t]) || 0; if (n > bestN) { bestN = n; best = t; tie = false; } else if (n === bestN) tie = true; }
          if (!tie && bestN > 0) { fixes.push(tok + '→' + best); return best; }
        }
        return tok; // 不唯一 → 绝不盲改
      }
    }
    fixes.push(tok + '→' + cands[0]);
    return cands[0];
  }).join('');
}

