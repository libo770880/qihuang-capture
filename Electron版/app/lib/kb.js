// 炮制/制法前缀全集（多字 HERB_PRE_TOKENS + 单字扩展，见 OCR_SINGLE_PREFIX）
const HERB_ALIAS_PREFIX = new Set([...HERB_PRE_TOKENS, ...OCR_SINGLE_PREFIX]);

// 药名写法分类：北柴胡/南柴胡（商品规格）、姜厚朴/法半夏（炮制品）是医师的**有意写法**，
// 与正名的差异不是 OCR 错字 —— 用量核查等处据此决定提示口径，绝不可说「系OCR形近错字」。
// 返回：null = 库内无此名（此时才谈得上纠错）；'炮制' = 炮制品写法；'规格' = 别名/商品规格。
// 注意：分类只影响提示文案，不参与任何文本改写（改写仍走 cleanSet/canon 既有链路）。
function herbAliasKind(name) {
  const n = String(name || '');
  if (!n) return null;
  const keys = getCleanCanonKeys();
  if (!keys.includes(n)) return null;          // 不在干净键集 → 可能是错字，交回纠错链路判断
  const canon = getCanon()[n];
  if (canon && canon !== n) {
    for (const pre of HERB_ALIAS_PREFIX) {
      if (pre.length >= n.length) continue;
      if (!n.startsWith(pre)) continue;
      const rest = n.slice(pre.length);
      if (rest === canon || keys.includes(rest)) return '炮制';
    }
  }
  return '规格';
}

// 方剂：内置（被用户同名覆盖则剔除）+ 用户方剂（均带 origin 出处）
function getAllFormulas() {
  const userNames = new Set(USER_FORMULAS.map(f => f.n));
  const builtin = BUILTIN_FORMULAS.filter(f => !userNames.has(f.n))
    .map(f => ({ ...f, user: false, overrides: false, origin: f.origin || FORMULA_ORIGIN[f.n] || '' }));
  return builtin.concat(USER_FORMULAS.map(f => ({ ...f, user: true, overrides: BUILTIN_FORMULAS.some(b => b.n === f.n), origin: f.origin || FORMULA_ORIGIN[f.n] || '' })));
}
// 仅内置库视图（供参照库同步进 data.db；不含用户库、不叠加 OCR 别名，保证「参照/用户」两层数据分离）
function getBuiltinHerbs() {
  return BUILTIN_HERB_ROWS.map(row => {
    const n = row[0];
    const origin = row[8] || HERB_ORIGIN[n] || '';
    const sx = herbCat.symptomsOf(row[3], row[5]);
    return {
      n, aliases: (row[1] || []).slice(), prop: row[2], fx: row[3], use: row[4], note: row[5],
      pre: row[6] || 0, tox: row[7] || 0, user: false, origin, source: origin,
      category: herbCat.classifyHerb(n, row[3]), indications: sx.join('、')
    };
  });
}
function getBuiltinFormulas() {
  return BUILTIN_FORMULAS.map(f => ({ ...f, user: false, overrides: false, origin: f.origin || FORMULA_ORIGIN[f.n] || '' }));
}

function getAllHerbs() {
  const names = new Set();
  const list = [];
  for (const row of BUILTIN_HERB_ROWS) {
    const n = row[0];
    if (USER_HERBS.some(h => h.n === n)) continue; // 被用户覆盖
    names.add(n);
    const origin = row[8] || HERB_ORIGIN[n] || '';
    const category = herbCat.classifyHerb(n, row[3]);
    const sx = herbCat.symptomsOf(row[3], row[5]);
    list.push({ n, aliases: row[1] || [], prop: row[2], fx: row[3], use: row[4], note: row[5], pre: row[6] || 0, tox: row[7] || 0, user: false, origin, source: origin, category, indications: sx.join('、'), sx });
  }
  for (const h of USER_HERBS) list.push({ ...h, user: true, category: h.category || herbCat.classifyHerb(h.n, h.fx), indications: h.indications || herbCat.symptomsOf(h.fx, h.note).join('、') });
  // 附带 OCR 错字别名（供前端组成块详情匹配），并标记 ocr 集合以便 UI 标注「已纠正」
  for (const h of list) {
    const ocr = ocrAliasesFor(h.n, h.aliases);
    if (ocr.length) {
      h.aliases = [...(h.aliases || []), ...ocr];
      h.ocr = {}; for (const a of ocr) h.ocr[a] = true;
    }
  }
  return list;
}

