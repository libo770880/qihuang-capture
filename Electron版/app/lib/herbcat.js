// 推断分类：覆盖表 → 功效规则 → 未分类
function classifyHerb(name, fx) {
  if (name && CAT_OVERRIDES[name]) return CAT_OVERRIDES[name];
  const text = String(fx || '');
  if (text) {
    for (const [cat, re] of CAT_RULES) {
      if (re.test(text)) return cat;
    }
  }
  return '未分类';
}

// 提取主治症状参考（功效为主、注意为辅；按症状表顺序去重，最多 12 个）
function symptomsOf(fx, note) {
  const fxText = String(fx || '');
  const allText = fxText + ' ' + String(note || '');
  const out = [];
  for (const [sym, re] of SYMPTOM_PATTERNS) {
    if (re.test(allText) && !out.includes(sym)) out.push(sym);
    if (out.length >= 12) break;
  }
  return out;
}

