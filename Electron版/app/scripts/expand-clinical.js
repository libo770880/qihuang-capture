function readJson(f) { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { return []; } }
function writeJson(f, arr) { fs.writeFileSync(f, JSON.stringify(arr, null, 1), 'utf8'); }
function merge(cur, add, key) {
  const map = new Map(cur.map(x => [x[key], x]));
  let added = 0;
  for (const it of add) { if (!map.has(it[key])) { map.set(it[key], it); added++; } }
  return { list: [...map.values()], added };
}

